/** "mayo, junio y agosto" */
export function listaMeses(indices: number[], lang: Lang): string {
  const n = indices.map((i) => MESES[lang][i]);
  if (n.length <= 1) return n.join('');
  return `${n.slice(0, -1).join(', ')} ${Y[lang]} ${n[n.length - 1]}`;
}
