/** Dirección de una página en un idioma. `ruta` sin barra inicial: '' (portada) o 'el-calafate/'. */
export function url(lang: Lang, ruta = ''): string {
  const base = import.meta.env.BASE_URL.replace(/\/?$/, '/');
  return lang === idiomaPorDefecto ? `${base}${ruta}` : `${base}${lang}/${ruta}`;
}

/** Elige el texto del idioma, con el español como respaldo. */
export function tr<T>(campo: Record<string, T> | T, lang: Lang): T {
  if (campo && typeof campo === 'object' && !Array.isArray(campo) && 'es' in (campo as object)) {
    const c = campo as Record<string, T>;
    return c[lang] ?? c.es;
  }
  return campo as T;
}

export const numero = (v: number, lang: Lang, dec = 0) =>
  v.toLocaleString(locale[lang], { maximumFractionDigits: dec });

